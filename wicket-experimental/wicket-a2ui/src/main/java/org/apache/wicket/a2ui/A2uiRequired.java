package org.apache.wicket.a2ui;

import java.lang.annotation.Documented;
import java.lang.annotation.ElementType;
import java.lang.annotation.Retention;
import java.lang.annotation.RetentionPolicy;
import java.lang.annotation.Target;

/**
 * Marks a component property the agent has to provide. A component that arrives without it is not
 * rendered. Properties without this annotation are {@code null} when absent, or zero and
 * {@code false} for primitives.
 *
 * @since 12.0.0
 */
@Documented
@Retention(RetentionPolicy.RUNTIME)
@Target(ElementType.RECORD_COMPONENT)
public @interface A2uiRequired
{
}
